<div class="p-4">
    <h2 class="h4 mb-3">Что делает этот фид</h2>
    <p class="mb-4">
        Сейчас формируется черновой XML-фид DomClick только на основе уже существующих полей сайта.
        Его можно использовать для первичной проверки формата и структуры, но он ещё не полностью
        соответствует требованиям Домклик.
    </p>

    <h3 class="h5 mb-2">Что уже попадает в фид</h3>
    <ul class="mb-4">
        <li>По каждому ЖК: название и адрес.</li>
        <li>По корпусу: условно один корпус на ЖК, с названием и адресом ЖК.</li>
        <li>По каждой квартире: ID, номер, этаж, количество комнат.</li>
        <li>Цена: только базовая цена квартиры.</li>
        <li>Площади: общая, жилая, кухня.</li>
        <li>Планировка: основное изображение планировки.</li>
        <li>Дополнительно: вид из окна и высота потолков, если заполнены.</li>
    </ul>

    <h3 class="h5 mb-2">Что пока не реализовано</h3>
    <p class="mb-2">Для полного соответствия требованиям Домклик ещё нужно добавить:</p>
    <ul class="mb-4">
        <li>Отдельные DomClick-ID для комплексов и корпусов.</li>
        <li>Координаты (широта/долгота) для ЖК, корпусов и офиса продаж.</li>
        <li>Признак соответствия ФЗ-214 по корпусу.</li>
        <li>Структуру помещений: площади комнат (<code>rooms_area</code>).</li>
        <li>Информацию об офисе продаж: телефон, адрес, часовой пояс, график работы.</li>
        <li>Информацию о застройщике: ID в DomClick, название, сайт, логотип.</li>
        <li>Опционально: акции, условия покупки и типы отделки.</li>
    </ul>

    <p class="text-muted mb-0">
        После появления этих данных в админке генератор фида можно расширить, не меняя эту кнопку
        и URL фида. Текущая версия предназначена для согласования формата и отладки.
    </p>
</div>

