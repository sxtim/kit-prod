<div class="p-4">
    <h2 class="h4 mb-3">Что делает этот фид</h2>
    <p class="mb-4">
        Формируется отдельный XML-фид для каталога новостроек Сити-центра.
        Текущий фид DomClick не меняется и остаётся доступен по своей ссылке.
    </p>

    <h3 class="h5 mb-2">Публичная ссылка</h3>
    <p class="mb-4">
        Сити-центр будет забирать файл по ссылке <code>/feeds/citycenter_feed.xml</code>.
        Чтобы обновить фид после изменений на сайте, нажмите «Сформировать и опубликовать».
    </p>

    <h3 class="h5 mb-2">Что попадает в фид</h3>
    <ul class="mb-4">
        <li>Выгружаются только активные квартиры.</li>
        <li>ЖК группируются по названию: один <code>complex</code> для «ЖК Спутник».</li>
        <li>Адресные записи ЖК выгружаются как здания внутри комплекса.</li>
        <li>По ЖК передаётся <code>complex_id</code>, по зданию — <code>building_id</code>.</li>
        <li>По квартире передаются ID, номер, этаж, комнатность, цена и площади.</li>
        <li>Изображения: планировка, поэтажный план, генплан и план с размерами, если заполнены.</li>
        <li>Дополнительно: вид из окна, высота потолков и срок сдачи, если заполнены.</li>
    </ul>

    <h3 class="h5 mb-2">Важно</h3>
    <p class="text-muted mb-0">
        Проданные и неактивные квартиры в этот фид не попадают. Это согласованное отличие от идеи полной шахматки.
    </p>
</div>
